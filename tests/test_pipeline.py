"""
tests/test_pipeline.py

Real assertions against the actual pipeline outputs in output/metrics.json,
generated by run_all.py. Run `python run_all.py` before `pytest -q` (run_all
is also invoked once as a session fixture here if metrics.json is missing).
"""

import json
import os
import subprocess
import sys

import pytest

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
METRICS_PATH = os.path.join(REPO_ROOT, "output", "metrics.json")


@pytest.fixture(scope="session", autouse=True)
def ensure_pipeline_has_run():
    if not os.path.exists(METRICS_PATH):
        subprocess.run([sys.executable, "run_all.py"], cwd=REPO_ROOT, check=True)


@pytest.fixture(scope="session")
def metrics():
    with open(METRICS_PATH) as f:
        return json.load(f)


def test_dataset_shape(metrics):
    assert metrics["n_train"] + metrics["n_test"] > 0
    # realistic rare-disease cohort sample size (300-500 patients)
    total_patients = metrics["n_train"] + metrics["n_test"]
    assert 300 <= total_patients <= 500
    assert metrics["n_true_biomarkers_injected"] == 18


def test_random_forest_auc_in_reasonable_band(metrics):
    auc = metrics["random_forest_auc"]
    assert 0.80 <= auc <= 0.98, f"Random Forest AUC {auc} outside expected band"


def test_gradient_boosting_auc_in_reasonable_band(metrics):
    auc = metrics["gradient_boosting_auc"]
    assert 0.80 <= auc <= 0.98, (
        f"{metrics['gradient_boosting_model']} AUC {auc} outside expected band"
    )


def test_top_18_biomarkers_identified(metrics):
    assert len(metrics["top_biomarkers"]) == 18
    assert len(set(metrics["top_biomarkers"])) == 18  # no duplicates


def test_biomarker_recovery_rate_is_meaningful(metrics):
    # recovery of truly-injected biomarkers should be well above chance
    # (18/200 features selected at random would recover ~1.6 on average)
    assert metrics["recovery_rate"] > 0.3
    assert len(metrics["recovered_biomarkers"]) >= 6


def test_injected_sanity_check_true_feature_beats_noise(metrics):
    sanity = metrics["sanity_true_beats_noise_example"]
    assert sanity["passes"] is True
    assert sanity["true_feature_score"] > sanity["noise_feature_score"]


def test_decision_support_examples_are_real(metrics):
    decision_path = os.path.join(REPO_ROOT, "output", "decision_support_examples.json")
    assert os.path.exists(decision_path)
    with open(decision_path) as f:
        examples = json.load(f)
    assert len(examples) >= 3
    for ex in examples:
        assert 0.0 <= ex["predicted_risk"] <= 1.0
        assert ex["predicted_label"] in (0, 1)
        assert len(ex["top_contributing_biomarkers"]) > 0
        for contrib in ex["top_contributing_biomarkers"]:
            assert "biomarker" in contrib and "risk_contribution" in contrib
